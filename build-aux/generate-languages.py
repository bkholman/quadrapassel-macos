"""Generate the language registry from upstream LINGUAS and native display names."""
import json
from pathlib import Path
import sys


def languages(metadata, linguas):
    entries = json.loads(Path(metadata).read_text())
    codes = [row[0] for row in entries]
    tags = [row[2].lower() for row in entries]
    if len(codes) != len(set(codes)) or len(tags) != len(set(tags)):
        raise ValueError("Duplicate language code or macOS language tag")
    supported = {"en"}
    for line in Path(linguas).read_text().splitlines():
        supported.update(line.split("#", 1)[0].split())
    missing = supported - set(codes)
    if missing:
        raise ValueError(f"Add native names for these languages: {sorted(missing)}")
    return [row for row in entries if row[0] in supported]


if __name__ == "__main__":
    rows = languages(sys.argv[1], sys.argv[2])
    lines = ["// Generated by build-aux/generate-languages.py; do not edit.",
             "namespace LanguageCatalog {", "    public LanguageInfo[] all () {", "        return {"]
    for row in rows:
        values = ", ".join(json.dumps(value, ensure_ascii=False) for value in row)
        lines.append(f"            new LanguageInfo ({values}),")
    lines += ["        };", "    }", "}", ""]
    Path(sys.argv[3]).write_text("\n".join(lines))
